import { describe, expect, it } from "vitest"
import { isNoOpBotComment } from "./botComments.js"

// Bodies trimmed from real comments these bots posted on phaenixorg PRs.
const OPLANE_ALL_SATISFIED = `<!-- oplane-security-review:oplane-bot:results -->
### Oplane Security Review

Oplane identified security requirements relevant to this PR and checked the implementation against them. All requirements are satisfied. Review the <a href="https://gravity.oplane.io/x">generated threat model</a>.

<table><tbody><tr><td nowrap>:green_circle: Implemented</td><td>Authorization Check</td></tr></tbody></table>`

const OPLANE_NONE_IDENTIFIED = `<!-- oplane-security-review:oplane-bot:results -->
### Oplane Security Review

Oplane reviewed this PR and did not identify any security requirements that need attention. Review the <a href="https://gravity.oplane.io/x">generated threat model</a>.`

const OPLANE_NEEDS_ATTENTION = `<!-- oplane-security-review:oplane-bot:results -->
### Oplane Security Review

Oplane identified security requirements relevant to this PR and checked the implementation against them, finding that **1 requirement needs attention**. Push changes to rerun the review.

<table><tbody><tr><td nowrap>:orange_circle: Partially implemented</td><td>Safe Rendering of Dashboard URL</td></tr></tbody></table>`

const OPLANE_UPDATING = `<!-- oplane-security-review:oplane-bot:results -->
### Oplane Security Review

> ⏳ **Update in progress** — a fresh review is running; this comment will refresh when it completes.

Oplane identified security requirements relevant to this PR and checked the implementation against them, finding that **1 requirement needs attention**.`

const OPLANE_IN_PROGRESS = `<!-- oplane-security-review:oplane-bot:in-progress -->
## ⏳ Oplane Security Review In Progress

A security review has been started for this pull request. Results will appear here when complete.`

const OPLANE_MAX_REVIEWS = `<!-- oplane-security-review:oplane-bot:max-reviews -->
**Oplane Security Review**

The maximum number of automatic reviews for this pull request has been reached.`

const codexSummary = (state: string) => `<!-- codex-pull-request-review-summary -->
<!-- codex-review-state:v1 ${state} -->
## Codex Review Summary

This comment shows the latest Codex review activity on this pull request.`

const CODEX_RUNNING = codexSummary(`{"code_review":{"commit_sha":"60c88a3","has_any_findings":null,"has_unresolved_findings":null,"status":"running"},"security_review":{"commit_sha":"60c88a3","has_any_findings":null,"has_unresolved_findings":null,"status":"running"}}`)
const CODEX_CLEAN = codexSummary(`{"code_review":{"commit_sha":"8c818e7","has_any_findings":false,"has_unresolved_findings":false,"status":"completed"},"security_review":{"commit_sha":"8c818e7","has_any_findings":null,"has_unresolved_findings":null,"status":"running"}}`)
const CODEX_WITH_FINDINGS = codexSummary(`{"code_review":{"commit_sha":"8c818e7","has_any_findings":true,"has_unresolved_findings":true,"status":"completed"}}`)

const CODEX_FINDING = `**<sub><sub>![P2 Badge](https://img.shields.io/badge/P2-yellow?style=flat)</sub></sub>  Fail when the live Hermes image lookup fails**

When the Cloud Run lookup fails, \`|| true\` converts the error into an empty \`image\`.

<!-- codex-code-review-finding:v1 -->`

describe("isNoOpBotComment", () => {
  it("skips Oplane all-clear results, status stubs and refreshes", () => {
    for (const body of [OPLANE_ALL_SATISFIED, OPLANE_NONE_IDENTIFIED, OPLANE_UPDATING, OPLANE_IN_PROGRESS, OPLANE_MAX_REVIEWS]) {
      expect(isNoOpBotComment("oplane-bot[bot]", body)).toBe(true)
    }
  })

  it("keeps Oplane results with unsatisfied requirements", () => {
    expect(isNoOpBotComment("oplane-bot[bot]", OPLANE_NEEDS_ATTENTION)).toBe(false)
  })

  it("skips Codex summaries that are running or found nothing", () => {
    expect(isNoOpBotComment("chatgpt-codex-connector[bot]", CODEX_RUNNING)).toBe(true)
    expect(isNoOpBotComment("chatgpt-codex-connector[bot]", CODEX_CLEAN)).toBe(true)
  })

  it("keeps Codex findings and summaries reporting unresolved findings", () => {
    // Review-thread comments come from GraphQL, which drops the [bot] suffix.
    expect(isNoOpBotComment("chatgpt-codex-connector", CODEX_FINDING)).toBe(false)
    expect(isNoOpBotComment("chatgpt-codex-connector[bot]", CODEX_WITH_FINDINGS)).toBe(false)
  })

  it("skips Claude PR review 'No new findings' but keeps reported findings", () => {
    expect(isNoOpBotComment("github-actions[bot]", "No new findings.\n\n> Generated by Claude PR review")).toBe(true)
    expect(isNoOpBotComment("github-actions[bot]", "1 new finding: 1 Low.\n\n> Generated by Claude PR review")).toBe(false)
  })

  it("skips Bugbot status notices and Linear linkbacks", () => {
    expect(isNoOpBotComment("cursor[bot]", "<h3>Bugbot couldn't run</h3>\n\nBugbot is not enabled for your user on this team.")).toBe(true)
    expect(isNoOpBotComment("cursor[bot]", "<h3>Bugbot is paused — on-demand spend limit reached</h3>")).toBe(true)
    expect(isNoOpBotComment("cursor", "### Cancel uses live org gate\n\n**Medium Severity**")).toBe(false)
    expect(isNoOpBotComment("linear[bot]", "<!-- linear-linkback -->\n<p>ENG-1</p>")).toBe(true)
  })

  it("never skips humans, even when they echo bot wording", () => {
    expect(isNoOpBotComment("viktor", "No new findings.")).toBe(false)
    expect(isNoOpBotComment("viktor", OPLANE_ALL_SATISFIED)).toBe(false)
  })
})
